W, H = A4
M = 42
CW = W - M * 2
styles = {
    'p': ParagraphStyle('body', fontName='Arial', fontSize=10.5, leading=14.5, textColor=colors.HexColor('#20333b'), spaceAfter=10),
    'h': ParagraphStyle('heading', fontName='Arial-Bold', fontSize=13, leading=17, textColor=colors.HexColor('#023747'), spaceAfter=8),
    'note': ParagraphStyle('note', fontName='Arial', fontSize=9.5, leading=13.5, textColor=colors.HexColor('#465e69'), spaceAfter=10),
    'code': ParagraphStyle('code', fontName='Arial', fontSize=10, leading=15, textColor=colors.HexColor('#007c9b'), spaceAfter=10),
}
c = canvas.Canvas(str(OUT), pagesize=A4)
c.setTitle('MotorSky - инструкция по добавлению товаров')
c.setAuthor('MotorSky')
text_source = ['# MotorSky: инструкция по добавлению товаров\n']
for number, page in enumerate(PAGES, 1):
    c.setFillColor(colors.HexColor('#10ABE3'))
    c.rect(0, H - 9, W, 9, stroke=0, fill=1)
    c.setFont('Arial-Bold', 10)
    c.setFillColor(colors.HexColor('#007c9b'))
    c.drawString(M, H - 38, 'MOTORSKY / РАБОТА С КАТАЛОГОМ')
    c.setFillColor(colors.HexColor('#102e3b'))
    c.setFont('Arial-Bold', 21)
    c.drawString(M, H - 76, page['title'])
    c.setFont('Arial', 9.5)
    c.setFillColor(colors.HexColor('#637c86'))
    c.drawString(M, H - 96, page['subtitle'])
    c.bookmarkPage('page' + str(number))
    c.addOutlineEntry(page['title'], 'page' + str(number))
    y = H - 121
    text_source += ['\n## ' + page['title'] + '\n']
    def paragraphs(items):
        global y
        for kind, text in items:
            p = Paragraph(text, styles[kind])
            _, height = p.wrap(CW, H)
            if y - height < 55:
                raise ValueError(f'Page {number} overflow: {text[:50]}')
            if kind == 'note':
                c.setFillColor(colors.HexColor('#edf7fa'))
                c.roundRect(M - 5, y - height - 5, CW + 10, height + 10, 4, fill=1, stroke=0)
            p.drawOn(c, M, y - height)
            y -= height + styles[kind].spaceAfter + (4 if kind == 'note' else 0)
            text_source.append(text.replace('<br/>', '\n') + '\n')
    paragraphs(page.get('before', []))
    if page.get('image'):
        img_path = SHOTS / (page['image'] + '.jpg')
        iw, ih = Image.open(img_path).size
        scale = min(CW / iw, page['max_h'] / ih)
        dw, dh = iw * scale, ih * scale
        c.setStrokeColor(colors.HexColor('#d7e2e7'))
        c.rect(M + (CW - dw) / 2 - 1, y - dh - 1, dw + 2, dh + 2, stroke=1, fill=0)
        c.drawImage(str(img_path), M + (CW - dw) / 2, y - dh, dw, dh)
        y -= dh + 17
    paragraphs(page.get('after', []))
    c.setStrokeColor(colors.HexColor('#d7e2e7'))
    c.line(M, 40, W - M, 40)
    c.setFillColor(colors.HexColor('#637c86'))
    c.setFont('Arial', 8)
    c.drawString(M, 26, 'MotorSky • Инструкция редактору • 20.10.2026')
    c.drawRightString(W - M, 26, f'{number} / {len(PAGES)}')
    c.showPage()
c.save()
(ROOT / 'output/product-guide/instruction.md').write_text('\n'.join(text_source), encoding='utf-8')
reader = PdfReader(OUT)
assert len(reader.pages) == len(PAGES)
for index, page in enumerate(reader.pages, 1):
    assert len(page.extract_text()) > 200, f'Missing text on page {index}'
print(f'Created and text-checked {OUT}: {len(reader.pages)} pages')
